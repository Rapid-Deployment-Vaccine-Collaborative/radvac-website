// One-off importer: pulls the RaDVaC Researchers Map KML from Google My Maps,
// geocodes each placemark's address via OpenStreetMap Nominatim, and writes
// src/data/researchers.ts. Re-run if the upstream Google map is updated.
//
// Usage: node scripts/import-researchers-map.mjs
//
// The KML has no <Point>/<coordinates> (Google geocodes server-side), so we
// geocode addresses ourselves. Nominatim asks for ~1 req/sec and a real UA.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { execSync } from "node:child_process";
import path from "node:path";

const KML_URL =
  "https://www.google.com/maps/d/kml?mid=1s5PSVi56YS2sGOSri5G8jEdDFeH0kHEs&forcekml=1";
const OUT_PATH = path.resolve("src/data/researchers.ts");
const CACHE_PATH = path.resolve("scripts/.geocode-cache.json");
const KML_CACHE = path.resolve("scripts/.researchers.kml");
const UA = "RaDVaC-website-importer/1.0 (info@radvac.org)";

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function decodeEntities(s) {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)));
}

function tag(block, name) {
  const m = block.match(new RegExp(`<${name}>([\\s\\S]*?)<\\/${name}>`));
  if (!m) return "";
  let v = m[1];
  const cdata = v.match(/^<!\[CDATA\[([\s\S]*?)\]\]>$/);
  if (cdata) v = cdata[1];
  return decodeEntities(v).trim();
}

function dataField(block, name) {
  const re = new RegExp(
    `<Data name="${name.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\$&")}">[\\s\\S]*?<value\\s*\\/?>([\\s\\S]*?)<\\/value>`
  );
  const m = block.match(re);
  if (!m) {
    // self-closing <value/>
    const re2 = new RegExp(
      `<Data name="${name.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\$&")}">[\\s\\S]*?<value\\s*\\/>`
    );
    if (re2.test(block)) return "";
    return "";
  }
  return decodeEntities(m[1]).trim();
}

function parsePlacemarks(kml) {
  const out = [];
  const re = /<Placemark>([\s\S]*?)<\/Placemark>/g;
  let m;
  while ((m = re.exec(kml))) {
    const block = m[1];
    out.push({
      name: tag(block, "name"),
      address: tag(block, "address"),
      email: dataField(block, "Contact email"),
      city: dataField(block, "City"),
      state: dataField(block, "State or Province"),
      country: dataField(block, "Country"),
      scienceDegree: dataField(block, "Science degree / education?"),
      labSkills: dataField(block, "Basic lab skills?"),
      labSpace: dataField(block, "Lab space?"),
      notes: dataField(block, "Other info"),
    });
  }
  return out;
}

async function loadCache() {
  if (!existsSync(CACHE_PATH)) return {};
  try {
    return JSON.parse(await readFile(CACHE_PATH, "utf8"));
  } catch {
    return {};
  }
}

async function saveCache(cache) {
  await writeFile(CACHE_PATH, JSON.stringify(cache, null, 2));
}

async function geocode(query) {
  const url = `https://nominatim.openstreetmap.org/search?format=json&limit=1&q=${encodeURIComponent(query)}`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`nominatim ${res.status} for "${query}"`);
  const data = await res.json();
  if (!data.length) return null;
  return { lat: parseFloat(data[0].lat), lng: parseFloat(data[0].lon) };
}

function yn(v) {
  if (!v) return undefined;
  return /^yes$/i.test(v) ? true : /^no$/i.test(v) ? false : undefined;
}

function slugId(name, idx) {
  const s = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 32);
  return `${s || "researcher"}-${idx}`;
}

function tsLiteral(v) {
  if (v === undefined) return undefined;
  if (typeof v === "string") return JSON.stringify(v);
  return String(v);
}

function emit(researchers) {
  const lines = [
    "// AUTO-GENERATED by scripts/import-researchers-map.mjs",
    "// Source: Google My Maps mid=1s5PSVi56YS2sGOSri5G8jEdDFeH0kHEs",
    "// Re-run the script to refresh, or hand-edit this file for small fixes.",
    "",
    "export interface Researcher {",
    "  id: string;",
    "  name: string;",
    "  email?: string;",
    "  city?: string;",
    "  state?: string;",
    "  country?: string;",
    "  scienceDegree?: boolean;",
    "  labSkills?: boolean;",
    "  labSpace?: boolean;",
    "  notes?: string;",
    "  lat: number;",
    "  lng: number;",
    "}",
    "",
    "export const researchers: Researcher[] = [",
  ];
  for (const r of researchers) {
    const parts = [`    id: ${tsLiteral(r.id)}`, `    name: ${tsLiteral(r.name)}`];
    if (r.email) parts.push(`    email: ${tsLiteral(r.email)}`);
    if (r.city) parts.push(`    city: ${tsLiteral(r.city)}`);
    if (r.state) parts.push(`    state: ${tsLiteral(r.state)}`);
    if (r.country) parts.push(`    country: ${tsLiteral(r.country)}`);
    if (r.scienceDegree !== undefined)
      parts.push(`    scienceDegree: ${r.scienceDegree}`);
    if (r.labSkills !== undefined) parts.push(`    labSkills: ${r.labSkills}`);
    if (r.labSpace !== undefined) parts.push(`    labSpace: ${r.labSpace}`);
    if (r.notes) parts.push(`    notes: ${tsLiteral(r.notes)}`);
    parts.push(`    lat: ${r.lat}`);
    parts.push(`    lng: ${r.lng}`);
    lines.push("  {");
    lines.push(parts.join(",\n") + ",");
    lines.push("  },");
  }
  lines.push("];", "");
  return lines.join("\n");
}

async function main() {
  let kml;
  if (existsSync(KML_CACHE)) {
    kml = await readFile(KML_CACHE, "utf8");
    console.log(`[kml] using cached ${KML_CACHE}`);
  } else {
    console.log(`[kml] fetching ${KML_URL}`);
    const res = await fetch(KML_URL, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`kml fetch ${res.status}`);
    kml = await res.text();
    await writeFile(KML_CACHE, kml);
  }

  const placemarks = parsePlacemarks(kml);
  console.log(`[kml] parsed ${placemarks.length} placemarks`);

  const cache = await loadCache();
  const researchers = [];
  for (let i = 0; i < placemarks.length; i++) {
    const p = placemarks[i];
    const queries = [
      p.address,
      [p.city, p.state, p.country].filter(Boolean).join(", "),
      [p.city, p.country].filter(Boolean).join(", "),
      p.country,
    ].filter(Boolean);

    let coords = null;
    let usedQuery = null;
    for (const q of queries) {
      if (cache[q] !== undefined) {
        coords = cache[q];
        usedQuery = q;
        break;
      }
      try {
        coords = await geocode(q);
      } catch (e) {
        console.warn(`[geocode] error "${q}": ${e.message}`);
        coords = null;
      }
      cache[q] = coords;
      await saveCache(cache);
      await sleep(1100); // Nominatim politeness
      if (coords) {
        usedQuery = q;
        break;
      }
    }

    if (!coords) {
      console.warn(`[skip] ${i}: ${p.name} — no geocode for any of: ${queries.join(" | ")}`);
      continue;
    }
    console.log(`[ok]   ${i}: ${p.name} -> ${coords.lat},${coords.lng}  (${usedQuery})`);

    researchers.push({
      id: slugId(p.name, i),
      name: p.name,
      email: p.email || undefined,
      city: p.city || undefined,
      state: p.state || undefined,
      country: p.country || undefined,
      scienceDegree: yn(p.scienceDegree),
      labSkills: yn(p.labSkills),
      labSpace: yn(p.labSpace),
      notes: p.notes || undefined,
      lat: coords.lat,
      lng: coords.lng,
    });
  }

  await mkdir(path.dirname(OUT_PATH), { recursive: true });
  await writeFile(OUT_PATH, emit(researchers));
  console.log(`[out] wrote ${OUT_PATH} with ${researchers.length} entries`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
